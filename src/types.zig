pub const CPU = struct {
    memory: [0xFFFF]u8 = @splat(0),
    program_counter: u16 = 0,
    stack_pointer: u8 = 0xFD,
    accumulator: u8 = 0,
    register_x: u8 = 0,
    register_y: u8 = 0,
    status: ProcessorStatus = ProcessorStatus{},
};

pub const ProcessorStatus = struct {
    negative: bool = false,
    overflow: bool = false,
    ignored: bool = false,
    break_: bool = false,
    decimal: bool = false,
    interrupt: bool = false,
    zero: bool = false,
    carry: bool = false,
};

